"""JT-80x0 on VIBE FM, P2's check (Kris 23 Nov 2026): one list of events, written twice.
   p2.json   for the SDK's tools/wasmtest.mjs (events at block boundaries: t = block x 128 / rate, exactly as it compares)
   events.h  for ref.c, the same events at the same blocks for the engine built natively
The .wasm and ref.c must then give the same output hash (wasmtest's out_hash: FNV over every float's bits)."""
import json, sys
BLOCK, SECONDS = 128, 4.0
KEY0 = 48                       # vibe_notes(): key 0 = note 48 (keyboard octave 1)
# (block, kind, id, down, value): kind "key" (VIBE_EV_KEY, id 0..24), "pad" (program), "encB"/"encA" (program / bank +1)
EV = [(10, "key", 21, 1, 0.5), (10, "key", 9, 1, 1.0), (200, "key", 21, 0, 0), (230, "key", 9, 0, 0),
      (250, "pad", 3, 1, 0.8),
      (300, "key", 12, 1, 0.25), (300, "key", 16, 1, 0.5), (300, "key", 19, 1, 1.0),
      (700, "key", 12, 0, 0), (700, "key", 16, 0, 0), (700, "key", 19, 0, 0),
      (760, "encB", 5, 0, 1.0), (800, "key", 24, 1, 0.75), (1100, "key", 24, 0, 0),
      (1150, "encA", 4, 0, 1.0), (1160, "key", 0, 1, 1.0), (1300, "key", 0, 0, 0)]

def main(rate, out_json, out_h):
    steps, ref = [], []
    prog = 0
    for b, kind, i, down, v in EV:
        t = b * BLOCK / rate
        if kind == "key":
            steps.append({"t": t, "ev": [2, i, down, v]})
            if down:
                import struct
                f = struct.unpack("f", struct.pack("f", v))[0]
                vel = int(struct.unpack("f", struct.pack("f", struct.unpack("f", struct.pack("f", f * 126.0))[0] + 1.5))[0])
                ref.append((b, 1, KEY0 + i, max(1, min(127, vel))))
            else:
                ref.append((b, 2, KEY0 + i, 0))
        else:
            if kind == "pad": prog = prog // 16 * 16 + i
            elif kind == "encB": prog = (prog + 1) % 64
            else: prog = (prog + 16) % 64
            steps.append({"t": t, "ev": [1, i, 1, v] if kind == "pad" else [4, i, 0, v]})
            ref.append((b, 3, prog, 0))
    json.dump({"seconds": SECONDS, "steps": steps}, open(out_json, "w"))
    with open(out_h, "w") as h:
        h.write("/* generated by vibe/test/make_script.py: do not edit */\n")
        h.write(f"#define REF_RATE {rate}u\n#define REF_BLOCKS {int(-(-SECONDS * rate // BLOCK))}u\n")
        h.write("static const uint32_t REF_EV[][4] = {   /* block, 1 on / 2 off / 3 program, note or program, velocity */\n")
        for e in ref: h.write("    {%du, %du, %du, %du},\n" % e)
        h.write("};\n")

if __name__ == "__main__":
    main(int(sys.argv[1]), sys.argv[2], sys.argv[3])
