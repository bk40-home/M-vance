"""JT-80x0 on VIBE FM, P2b (Kris 24 Nov 2026): the 2x upsampler's half-band FIRs -> vibe/jt80x0/jt_up_coef.h.

  python3 tools/gen_vibe_up.py        (from the repo root; the output is committed)

A host at 88.2 / 96 kHz runs the engine at half its rate and doubles it (one stage); 176.4 / 192 kHz at a quarter (two).
Each stage is a Kaiser-windowed half-band FIR: h[c] = 1/2, h[c +- 2j] = 0, so the outputs alternate between the input
itself (delayed, untouched: the engine's samples pass bit for bit) and the odd phase, a P-tap sum. Normalised to the
stage's INPUT rate fs: pass to PASS x fs, stop from (1 - PASS) x fs (the images of what passes).
  stage 1  PASS 0.4535 (20 kHz at 44.1), 90 dB down from 0.5465 (24.1 kHz at 44.1, 26.2 kHz at 48)
  stage 2  the same pass band, 90 dB down from the first image of it: (1 - PASS / 2) x 2 fs
Checked here: pass-band ripple and the stop-band floor, on a dense grid. Pure Python (no numpy)."""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "vibe/jt80x0/jt_up_coef.h"
PASS = 0.4535                  # of the stage's input rate
ATT = 90.0                     # dB


def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-17 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def halfband(k):
    """length 4k + 3, centre c = 2k + 1; the odd phase: P = 2k + 2 taps (offsets c +- 1, 3, ..)"""
    n = 4 * k + 3
    c = (n - 1) // 2
    beta = 0.1102 * (ATT - 8.7)
    h = []
    for i in range(n):
        m = i - c
        s = 0.5 if m == 0 else math.sin(math.pi * m / 2) / (math.pi * m)
        w = i0(beta * math.sqrt(1 - (2 * i / (n - 1) - 1) ** 2)) / i0(beta)
        h.append(s * w)
    for i in range(n):          # exact zeros and the exact 1/2 at the centre: the even phase is a copy
        if (i - c) % 2 == 0:
            h[i] = 0.5 if i == c else 0.0
    return h


def resp(h, f):                 # |H| at f (of the OUTPUT rate, 0..0.5): 1 in the pass band (h sums to 1; the taps
    re = sum(x * math.cos(2 * math.pi * f * i) for i, x in enumerate(h))   # x 2 in the table make up for the zeros
    im = sum(x * math.sin(2 * math.pi * f * i) for i, x in enumerate(h))   # stuffed between the inputs)
    return math.hypot(re, im)


def design(name, pass_out, stop_out, k0):
    """the shortest half-band that meets pass_out (ripple) / stop_out (ATT), both as fractions of the OUTPUT rate"""
    for k in range(k0, 80):
        h = halfband(k)
        rip = max(abs(20 * math.log10(resp(h, pass_out * i / 400))) for i in range(401))
        stop = max(20 * math.log10(max(resp(h, stop_out + (0.5 - stop_out) * i / 400), 1e-12)) for i in range(401))
        if rip <= 0.01 and stop <= -ATT:
            print(f"gen_vibe_up: {name}: {len(h)} taps (odd phase {2 * k + 2}), ripple {rip:.4f} dB, stop {stop:.1f} dB")
            return h, rip, stop
    raise SystemExit(f"gen_vibe_up: {name}: no half-band up to 80 meets it")


def main():
    h1, r1, s1 = design("stage 1", PASS / 2, (1 - PASS) / 2, 4)
    h2, r2, s2 = design("stage 2", PASS / 4, (1 - PASS / 2) / 2, 1)
    W = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* GENERATED by tools/gen_vibe_up.py: do not edit. The 2x upsampler's half-band FIRs (JT-80x0 on VIBE FM, P2b):",
         " * each the odd phase only (the even phase is the input itself, delayed), oldest input first. */",
         "#pragma once"]
    for nm, h, r, s, what in (("JT_UP1", h1, r1, s1, "stage 1 (fs -> 2 fs): pass 0.4535 fs, stop 0.5465 fs"),
                              ("JT_UP2", h2, r2, s2, "stage 2 (2 fs -> 4 fs): pass 0.4535 fs, stop 1.77 fs")):
        c = (len(h) - 1) // 2
        odd = [2 * h[i] for i in range(len(h)) if (i - c) % 2]   # x 2: the interpolator's gain
        W.append(f"/* {what}: {len(h)} taps, ripple {r:.4f} dB, {-s:.1f} dB down */")
        W.append(f"#define {nm}_P {len(odd)}u")
        W.append(f"static const float {nm}[{len(odd)}] = {{")
        for i in range(0, len(odd), 4):
            W.append("    " + ", ".join(f"{v:.9e}f" for v in odd[i:i + 4]) + ",")
        W.append("};")
    OUT.write_text("\n".join(W) + "\n", encoding="utf-8")
    print(f"gen_vibe_up: {OUT.relative_to(OUT.parents[2])}")


if __name__ == "__main__":
    main()
