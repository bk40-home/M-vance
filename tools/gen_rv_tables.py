"""The plate reverb's knob laws, by knob value 0..127, for firmware/src/mv_reverb.c.

  python3 tools/gen_rv_tables.py        (run from the repo root; the output is committed)

Ported from the JT-8000's PlateReverb.cpp setters (Jteensy8000 src/core/dsp), evaluated in float32 exactly as the JT
does (norm = value / 127):
  SIZE      decay = 0.1 + 0.8995 (0.5 n + 0.5 n^2)                                  -> RV_DECAY  (Q30)
  HI DAMP   tank LP corner 18 kHz -> 800 Hz, exponential in n; 0 = bypass          -> RV_HIDAMP (Q31 coefficient)
  LO DAMP   tank HP corner 20 Hz -> 600 Hz; 0 = bypass                               -> RV_LODAMP
  LOWPASS   wet LP 20 kHz -> 500 Hz; 0 = off                                         -> RV_MLP
  HIPASS    wet HP 20 Hz -> 1 kHz; 0 = off                                           -> RV_MHP
  coefficient a = exp(-2 pi fc / fs) (the one-pole y = x + a (y - x)), 0 once fc >= 0.45 fs
The corners depend on the rate: tables for 44.1 kHz (the FM-1) and 48 kHz (the JT, for tools/compare/cmp_rv.cpp).
"""
import math, struct
from pathlib import Path

f32 = lambda v: struct.unpack('f', struct.pack('f', v))[0]

def coeff(fc, fs):
    if fc >= f32(fs * 0.45): return 0.0
    return f32(math.exp(f32(-6.28318531 * fc / fs)))

def sweep(n, lo, hi):
    return f32(lo * f32(math.pow(f32(hi / lo), n)))

out = ["/* generated by tools/gen_rv_tables.py from the JT-8000 PlateReverb setters: do not edit */",
       "/* by knob value 0..127: decay (Q30), one-pole coefficients (Q31; 0 = bypass) */", "#pragma once", "#include <stdint.h>", ""]
for fs in (44100, 48000):
    cols = {'RV_DECAY': [], 'RV_HIDAMP': [], 'RV_LODAMP': [], 'RV_MLP': [], 'RV_MHP': []}
    for v in range(128):
        n = f32(v / f32(127.0))
        shaped = f32(f32(0.5 * n) + f32(f32(0.5 * n) * n))
        cols['RV_DECAY'].append(round(f32(0.1 + f32(0.8995 * shaped)) * 2**30))
        for key, lo, hi in (('RV_HIDAMP', 18000.0, 800.0), ('RV_LODAMP', 20.0, 600.0),
                            ('RV_MLP', 20000.0, 500.0), ('RV_MHP', 20.0, 1000.0)):
            cols[key].append(round((coeff(sweep(n, lo, hi), fs) if n > 0.001 else 0.0) * 2**31))
    out.append(("#if" if fs == 44100 else "#elif") + f" MV_RV_FS == {fs}")
    for key, t in cols.items():
        typ = 'int32_t' if key == 'RV_DECAY' else 'uint32_t'
        out.append(f"static const {typ} {key}[128] = {{")
        for i in range(0, 128, 8):
            out.append("    " + ", ".join((f"{x}u" if typ == 'uint32_t' else str(x)) for x in t[i:i + 8]) + ",")
        out.append("};")
out += ["#else", '#error "mv_rv_tables.h: tables for 44100 / 48000 only"', "#endif", ""]
Path("firmware/gen/mv_rv_tables.h").write_text("\n".join(out))
print("gen_rv_tables: 5 x 128 x 2 rates -> firmware/gen/mv_rv_tables.h")
