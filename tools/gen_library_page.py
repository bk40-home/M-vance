import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "third_party/fm1-kit/tools"))
from build_library import build  # noqa: E402

OUT = ROOT / "docs/library.html"
OLD = ROOT / "docs/bank.html"
GEN = ROOT / "firmware/gen"
CLASSIC = ROOT / "build/library/bank-model.classic.js"
REDIRECT = """<!DOCTYPE html>
<!-- SPDX-License-Identifier: GPL-3.0-only. GENERATED by tools/gen_library_page.py: the bank page became library.html
     (the patch library) and sim/editor.html (the sound editor), Kris 15 Nov 2026 -->
<html lang="en"><head><meta charset="utf-8"><title>JT-80x0 library</title>
<meta http-equiv="refresh" content="0; url=library.html"></head>
<body style="font:14px system-ui,sans-serif;background:#0E0A06;color:#F5E8D6;margin:24px">
<p>The bank page is now the <a href="library.html" style="color:#FF8000">patch library</a>; sounds are edited in the
<a href="sim/editor.html" style="color:#FF8000">editor</a>.</p></body></html>
"""
# the parameters the library's details panel shows (enum names of firmware/gen/mv_params.h)
PREVIEW = ["OSC1_WAVE", "OSC2_WAVE", "FLT_TYPE", "FLT_SLOPE", "CUTOFF", "RESO", "AENV_A", "AENV_D", "AENV_S",
           "AENV_R", "MONO", "UNISON", "MFX_LEVEL", "DLY_LEVEL", "PORTA_SW"]
# the bank-model.js API the adapter and the mock use (FK.mvb)
API = ["PATCH", "NPERF", "PERF_DEF", "nameOf", "parseBankFile", "makeBankSyx", "perfMsgs", "soundOf", "soundCopy",
       "soundEqual", "itemFromSound", "tempArea", "applyTemp", "diffMsg"]


def c_array(text, name):
    """the numbers of `static const uint8_t NAME[..][..] = { .. };` (comments dropped)"""
    m = re.search(r"\b" + name + r"\s*\[[^]]*\]\s*\[[^]]*\]\s*=\s*\{(.*?)\n\};", text, re.S)
    if not m:
        raise SystemExit(f"gen_library_page: {name} not found in mv_factory.h")
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    return [int(x) for x in re.findall(r"\d+", body)]


def factory():
    """the 64 programs as the firmware holds them: hex strings (upper, lower, performance bytes)"""
    t = (GEN / "mv_factory.h").read_text()
    n = int(re.search(r"#define MV_NPROG (\d+)", t).group(1))
    up, lo, pf = c_array(t, "MV_FACTORY"), c_array(t, "MV_FACTORY_LO"), c_array(t, "MV_FACTORY_PERF")
    assert len(up) == n * 248 and len(lo) == n * 248 and len(pf) == n * 16, "mv_factory.h: unexpected sizes"
    hx = lambda a, k, w: bytes(a[k * w:(k + 1) * w]).hex()
    return [[hx(up, k, 248), hx(lo, k, 248), hx(pf, k, 16)] for k in range(n)]


def params():
    """MV_PARAMS as [off, size, min, max] (what mv_patch_sanitize clamps to), and the preview's: {NAME: [off, size],
    NAME_names: [..]} for the enum names in PREVIEW"""
    t = (GEN / "mv_params.h").read_text()
    ids = {m[1]: int(m[2]) for m in re.finditer(r"\bMV_P_(\w+)\s*=\s*(\d+)", t)}
    names = {m[1]: re.findall(r'"([^"]*)"', m[2]) for m in re.finditer(r"MV_N_(\w+)\[\]\s*=\s*\{([^}]*)\}", t)}
    tab = t[t.index("MV_PARAMS[MV_NPARAMS] = {"):]
    rows = re.findall(r"^\s*\{(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*\d+,\s*\d+,\s*\w+,\s*\w+,\s*\w+,\s*\d+,\s*\"[^\"]*\",\s*(\w+)\}",
                      tab, re.M)
    n = int(re.search(r"#define MV_NPARAMS (\d+)u", t).group(1))
    if len(rows) != n:
        raise SystemExit(f"gen_library_page: read {len(rows)} of MV_PARAMS' {n} rows")
    rng = [[int(r[0]), int(r[1]), int(r[2]), int(r[3])] for r in rows]
    pv = {}
    for k in PREVIEW:
        r = rows[ids[k]]
        pv[k] = [int(r[0]), int(r[1])]
        if r[4].startswith("MV_N_"):
            pv[k + "_names"] = names[r[4][5:]]
    return rng, pv


def classic():
    """sim/bank/bank-model.js as a plain script: FK.mvb = its API (the page's scripts are not modules)"""
    src = (ROOT / "sim/bank/bank-model.js").read_text()
    if re.search(r"^\s*import\b", src, re.M):
        raise SystemExit("gen_library_page: bank-model.js imports something: the plain-script copy cannot")
    body = re.sub(r"^export ", "", src, flags=re.M)
    CLASSIC.parent.mkdir(parents=True, exist_ok=True)
    CLASSIC.write_text("/* GENERATED by tools/gen_library_page.py from sim/bank/bank-model.js (its exports as FK.mvb) */\n"
                       "(function (G) {\n\"use strict\";\n" + body +
                       "\nG.FK = G.FK || {};\nG.FK.mvb = {" + ", ".join(API) + "};\n"
                       "})(typeof window !== \"undefined\" ? window : globalThis);\n")
    return CLASSIC


def version():
    """APP_VER of a release build (tools/build.py VERSION), else dev"""
    for line in (ROOT / "tools/build.py").read_text().splitlines():
        if line.startswith("VERSION") and "=" in line:
            v = line.split("=", 1)[1].split("#")[0].strip().strip("\"'")
            if v and v != "None":
                return v
    return "dev"


def main():
    rng, pv = params()
    data = {"factory": factory(), "params": rng, "pv": pv}
    lib = classic()
    if "--data" in sys.argv:
        out = Path(sys.argv[sys.argv.index("--data") + 1])
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(data))
        print(f"gen_library_page: {out} (the test's data); {lib.relative_to(ROOT)}")
        return
    n = build(OUT, data, [lib, ROOT / "library/adapter-mvance.js", ROOT / "library/mock-mvance.js"],
              stamp="JT-80x0 " + version())
    OLD.write_text(REDIRECT)
    print(f"gen_library_page: {OUT.relative_to(ROOT)} ({n} bytes, {len(data['factory'])} factory programs); "
          f"{OLD.relative_to(ROOT)} points to it")


if __name__ == "__main__":
    main()
